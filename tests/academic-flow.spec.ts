import { expect,test } from "@playwright/test"
import { randomUUID } from "node:crypto"

test("От импортированной работы до подтверждённой пересдачи, архива и учебной истории",async({page})=>{
  test.setTimeout(90000)
  const suffix=randomUUID().slice(0,8)
  const subject="Тестовая студия "+suffix
  const task="Учебный чертёж "+suffix
  const dialog=page.getByRole("dialog")
  const save=async()=>{await dialog.getByRole("button",{name:"Сохранить",exact:true}).click();await expect(dialog).toHaveCount(0)}
  await page.goto("/schedule")
  await page.getByRole("button",{name:"Импорт JSON"}).click()
  const ref={title:subject,semester:3}
  await dialog.getByLabel("Содержимое JSON").fill(JSON.stringify({version:1,origin:"Тестовый журнал",subjects:[ref],tasks:[{subject:ref,title:task}]}))
  await dialog.getByRole("button",{name:"Предварительный просмотр"}).click()
  await dialog.getByRole("button",{name:"Подтвердить запись (2)"}).click()
  await expect(dialog.getByRole("status")).toContainText("Записано: 2")
  await page.goto("/subjects")
  await page.getByRole("searchbox").fill(subject)
  await page.getByRole("link",{name:"Карточка дисциплины"}).click()
  await expect(page).toHaveURL(/subject=\d+/)
  const dossier=page.url()
  await expect(page.getByText(/Источник · Тестовый журнал/).filter({visible:true})).toBeVisible()
  await page.getByRole("link",{name:task,exact:true}).click()
  await dialog.getByRole("button",{name:"Изменить"}).click()
  await dialog.getByLabel("Подтверждённая задолженность").check()
  await save()
  await page.goto("/debts")
  await page.getByRole("listitem").filter({hasText:task}).getByRole("button",{name:"Назначить пересдачу"}).click()
  await dialog.getByLabel("Дата пересдачи").fill("2180-10-15")
  await save()
  await page.goto("/calendar?date=2180-10-15")
  await expect(page.getByText(task,{exact:true}).filter({visible:true})).toBeVisible()
  await page.getByRole("button",{name:"Добавить событие"}).click()
  await dialog.getByLabel("Название события").fill("Защита "+suffix)
  await dialog.getByLabel("Вид события").selectOption("Проектная защита")
  await save()
  await expect(page.getByText("Защита "+suffix,{exact:true}).filter({visible:true})).toBeVisible()
  await page.goto("/debts")
  await page.getByRole("listitem").filter({hasText:task}).getByRole("button",{name:"Внести итог"}).click()
  await dialog.getByLabel("Итог пересдачи").selectOption("Сдано")
  await save()
  await expect(page.getByRole("listitem").filter({hasText:task}).getByText("Сдано")).toBeVisible()
  await page.goto("/results")
  await page.getByRole("button",{name:"Записать результат"}).click()
  await dialog.getByLabel("Дисциплина").selectOption({label:subject+" · семестр 3"})
  await dialog.getByLabel("Вид результата").selectOption("Зачёт")
  await dialog.getByLabel("Работа или аттестация").fill("Учебная защита "+suffix)
  await dialog.getByLabel("Оценка или результат").fill("Зачтено")
  await dialog.getByLabel("Дата результата").fill("2180-10-15")
  await save()
  await page.goto("/debts")
  await page.getByRole("button",{name:"Добавить долг по дисциплине"}).click()
  await dialog.getByLabel("Дисциплина").selectOption({label:subject+" · семестр 3"})
  await dialog.getByLabel("Основание задолженности").fill("Учебный экзамен "+suffix)
  await dialog.getByLabel("Источник подтверждения").fill("Тестовая ведомость")
  await save()
  const debtRow=page.getByRole("listitem").filter({hasText:"Учебный экзамен "+suffix})
  await debtRow.getByRole("button",{name:"Назначить пересдачу"}).click()
  await dialog.getByLabel("Дата пересдачи").fill("2180-10-16")
  await save()
  await debtRow.getByRole("button",{name:"Внести итог"}).click()
  await dialog.getByLabel("Итог пересдачи").selectOption("Сдано")
  await save()
  await expect(debtRow.getByText("Сдано")).toBeVisible()
  await page.goto("/history")
  await page.getByRole("button",{name:"Указать учебный год"}).click()
  await dialog.getByLabel("Дисциплина").selectOption({label:subject+" · семестр 3"})
  await dialog.getByLabel("Год начала учебного года").fill("2179")
  await dialog.getByLabel("Курс",{exact:true}).fill("2")
  await save()
  await expect(page.getByRole("heading",{name:/2179.*2180.*курс 2.*семестр 3/})).toBeVisible()
  await page.goto(dossier)
  await expect(page.getByText("Зачтено",{exact:true}).filter({visible:true})).toBeVisible()
  await page.getByRole("link",{name:task,exact:true}).click()
  await expect(dialog.getByText("Принято",{exact:true})).toBeVisible()
  await dialog.getByRole("link",{name:"Прикрепить файл"}).click()
  await dialog.getByLabel("Название материала").fill("Памятка "+suffix)
  const bytes=Buffer.from("Synthetic file "+suffix)
  await dialog.getByLabel(/Оригинал файла/).setInputFiles({name:"notes.txt",mimeType:"text/plain",buffer:bytes})
  await dialog.getByLabel("Источник материала").fill("Тестовая методичка")
  await dialog.getByRole("button",{name:"Предварительный просмотр"}).click()
  await expect(dialog.getByRole("status")).toContainText("Тестовая методичка")
  await dialog.getByRole("button",{name:"Подтвердить добавление"}).click()
  await expect(dialog).toHaveCount(0)
  await page.goto(dossier)
  const download=page.getByRole("link",{name:"Памятка "+suffix})
  const response=await page.request.get((await download.getAttribute("href"))!)
  expect(response.ok()).toBeTruthy()
  expect(response.headers()["content-disposition"]).toContain("attachment")
  expect(await response.body()).toEqual(bytes)
  await page.goto("/")
  await page.getByRole("button",{name:"Добавить объявление"}).click()
  await dialog.getByLabel("Текст объявления").fill("Объявление "+suffix)
  await save()
  await expect(page.getByText("Объявление "+suffix,{exact:true}).filter({visible:true})).toBeVisible()
})
