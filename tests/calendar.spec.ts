import { expect, test } from "@playwright/test"
import { randomUUID } from "node:crypto"

test("Календарь открывается на сегодня, переключает месяц и возвращается к текущей дате", async ({page}) => {
  await page.goto("/calendar")
  const today = page.locator('a[aria-current="date"]')
  await expect(today).toBeVisible()
  const label = await today.getAttribute("aria-label")
  await page.getByRole("link",{name:"Следующий месяц"}).click()
  await expect(today).toHaveCount(0)
  await page.getByRole("link",{name:"Предыдущий месяц"}).click()
  await expect(today).toHaveAttribute("aria-label",label!)
  await page.getByRole("link",{name:"Сегодня",exact:true}).click()
  await expect(page).toHaveURL(new URL((await today.getAttribute("href"))!,page.url()).href)
})

test("Занятия, отмены, переносы, дедлайны и фильтры по выбранной дате", async ({page}) => {
  const subject = {title:"Календарь " + randomUUID(),semester:1}
  const task = "Датированное задание " + randomUUID()
  const undated = "Без дедлайна " + randomUUID()
  const lesson = {subject,teacher:"Тестовый преподаватель",date:"2199-03-31",pair:1,startTime:"09:00",endTime:"10:30",room:"Т1",subgroup:"II",lessonType:"Практика"}
  await page.goto("/schedule")
  await page.getByRole("button",{name:"Импорт JSON"}).click()
  const panel = page.getByRole("dialog")
  await panel.getByLabel("Содержимое JSON").fill(JSON.stringify({version:1,subjects:[subject],
    tasks:[{subject,title:task,deadline:lesson.date,priority:"Высокий"},{subject,title:undated}],
    lessons:[{...lesson,status:"Отменено"},{...lesson,pair:2,status:"Перенесено",movedDate:"2199-04-01",movedPair:3,movedStart:"13:00",movedEnd:"14:30"}]}))
  await panel.getByRole("button",{name:"Предварительный просмотр"}).click()
  await panel.getByRole("button",{name:"Подтвердить запись (5)"}).click()
  await expect(panel.getByRole("status")).toContainText("Записано: 5")
  await page.goto("/calendar?date=2199-03-01")
  await page.getByRole("link",{name:"31.03.2199. Занятий: 2. Заданий: 1"}).click()
  const summaries = page.locator("summary:visible")
  await summaries.filter({hasText:"Отменено"}).click()
  await expect(page.locator("details[open]").getByText("Тестовый преподаватель · ауд. Т1 · Подгруппа II")).toBeVisible()
  await page.getByRole("link",{name:"Только задания"}).click()
  await expect(summaries).toHaveCount(1)
  await summaries.filter({hasText:task}).click()
  await expect(page.getByText("Приоритет: Высокий")).toBeVisible()
  await expect(page.getByText("Статус: Не выяснено")).toBeVisible()
  await expect(page.getByText(undated)).toHaveCount(0)
  await page.getByRole("link",{name:"Карточка задания"}).click()
  await expect(page.getByRole("dialog").getByRole("heading",{name:task})).toBeVisible()
  await page.goto("/calendar?date=2199-03-31")
  await page.getByRole("link",{name:"Только занятия"}).click()
  await expect(summaries).toHaveCount(2)
  await summaries.filter({hasText:"Перенесено"}).click()
  await expect(page.getByText("Перенесено на 01.04.2199, 13:00–14:30")).toBeVisible()
  await page.getByRole("link",{name:"Следующий месяц"}).click()
  await expect(summaries).toHaveCount(1)
  if (!await page.locator("details[open] summary:visible").count()) await summaries.click()
  await expect(page.getByText("Перенесено с 31.03.2199, 09:00–10:30")).toBeVisible()
  await page.getByRole("link",{name:"Занятие в расписании"}).click()
  await expect(page).toHaveURL(/\/schedule\?week=.*#lesson-\d+-2199-04-01$/)
  await expect(page.locator(new URL(page.url()).hash)).toContainText(subject.title)
  await page.goto("/calendar?date=2199-04-14")
  await expect(page.getByText("Нет событий на выбранную дату.")).toBeVisible()
  await expect(page.getByRole("link",{name:"14.04.2199. Занятий: 0. Заданий: 0"})).toBeVisible()
})
