import { randomUUID } from "node:crypto"
import { expect, test, type Page } from "@playwright/test"

const fixtureName = (name: string) => `Тест · ${name} · ${randomUUID().slice(0, 8)}`
const dialog = (page: Page) => page.getByRole("dialog")

async function createSubject(page: Page, name = fixtureName("предмет")) {
  await page.goto("/subjects")
  await page.getByRole("button", { name: "Добавить предмет" }).click()
  await dialog(page).getByLabel("Название дисциплины").fill(name)
  await dialog(page).getByLabel("Семестр").fill("2")
  await dialog(page).getByRole("button", { name: "Сохранить" }).click()
  await expect(dialog(page)).toHaveCount(0)
  return name
}

async function subjectTasks(page: Page, name: string) {
  await page.goto("/subjects")
  await page.getByRole("searchbox").fill(name)
  await page.getByRole("link", { name: "Задания предмета" }).click()
  await expect(page.getByLabel("Фильтр по предмету").locator("option:checked")).toContainText(name)
}

async function createTask(page: Page, name: string, deadline?: string, priority = "Обычный") {
  await page.getByRole("button", { name: "Добавить задание" }).click()
  await dialog(page).getByLabel("Название задания").fill(name)
  await expect(dialog(page).getByLabel("Статус", { exact: true })).toHaveValue("Не выяснено")
  await dialog(page).getByLabel("Приоритет").selectOption(priority)
  if (deadline) await dialog(page).getByLabel("Срок сдачи").fill(deadline)
  await dialog(page).getByRole("button", { name: "Сохранить" }).click()
  await expect(dialog(page)).toHaveCount(0)
  await expect(page.getByRole("button", { name, exact: true })).toBeVisible()
}

test("Создание, поиск и редактирование предмета после перезагрузки", async ({ page }) => {
  const name = await createSubject(page)
  await page.getByRole("searchbox").fill(name.toUpperCase())
  await page.getByRole("button", { name: "Изменить" }).click()
  await dialog(page).getByLabel("Количество ЗЕТ").fill("2.5")
  await dialog(page).getByLabel("Заметки").fill("Проверка сохранения")
  await dialog(page).getByRole("button", { name: "Сохранить" }).click()
  await expect(dialog(page)).toHaveCount(0)
  await page.reload()
  await page.getByRole("searchbox").fill(name)
  await expect(page.getByText("2.5", { exact: true })).toBeVisible()
  await expect(page.getByText("Проверка сохранения")).toBeVisible()
  await page.getByRole("searchbox").fill(name + "xyz")
  await expect(page.getByText("По вашему запросу ничего не найдено")).toBeVisible()
})

test("Задание связано с предметом, неизвестный срок и новый статус сохраняются", async ({ page }) => {
  const subject = await createSubject(page)
  const other = await createSubject(page)
  await subjectTasks(page, subject)
  const name = fixtureName("задание")
  await createTask(page, name)
  await expect(page.getByText("Без срока")).toBeVisible()
  await page.getByRole("button", { name, exact: true }).click()
  await expect(dialog(page).getByText(subject, { exact: true })).toBeVisible()
  await dialog(page).getByRole("button", { name: "Изменить" }).click()
  await dialog(page).getByLabel("Статус", { exact: true }).selectOption("В процессе")
  await dialog(page).getByLabel("Описание и требования").fill("Проверка подробной карточки")
  await dialog(page).getByRole("button", { name: "Сохранить" }).click()
  await expect(dialog(page)).toHaveCount(0)
  await page.reload()
  await page.getByLabel("Фильтр по статусу").selectOption("Не начато")
  await expect(page.getByRole("button", { name, exact: true })).toHaveCount(0)
  await page.getByLabel("Фильтр по статусу").selectOption("В процессе")
  await page.getByRole("button", { name, exact: true }).click()
  await expect(dialog(page).getByText("Проверка подробной карточки")).toBeVisible()
  await expect(dialog(page).getByText("В процессе", { exact: true })).toBeVisible()
  await dialog(page).getByRole("button", { name: "Закрыть" }).click()
  await subjectTasks(page, other)
  await expect(page.getByRole("button", { name, exact: true })).toHaveCount(0)
})

test("Сортировка заданий и ближайший срок на главной", async ({ page }) => {
  const subject = await createSubject(page)
  await subjectTasks(page, subject)
  const first = fixtureName("со сроком")
  const later = fixtureName("позже")
  const urgent = fixtureName("без срока")
  await createTask(page, urgent, undefined, "Срочный")
  await createTask(page, later, "2099-05-20")
  await createTask(page, first, "2099-05-01")
  const taskNames = page.getByRole("button", { name: /^Тест ·/ })
  await expect(taskNames).toHaveText([first, later, urgent])
  await page.getByLabel("Сортировка").selectOption("priority")
  await expect(taskNames).toHaveText([urgent, first, later])
  await page.goto("/")
  const subjectsPanel = page.getByRole("region", { name: "Обзор дисциплин" })
  await expect(subjectsPanel.getByText(subject, { exact: true })).toBeVisible()
  const upcoming = page.getByRole("region", { name: "Ближайшие дедлайны" })
  await expect(upcoming.getByRole("link", { name: new RegExp(urgent) })).toHaveCount(0)
  await upcoming.getByRole("link", { name: new RegExp(first) }).click()
  await expect(dialog(page).getByRole("heading", { name: first })).toBeVisible()
})

test("Удаление с подтверждением защищает связанные задания", async ({ page }) => {
  const subject = await createSubject(page)
  await subjectTasks(page, subject)
  const name = fixtureName("удаление")
  await createTask(page, name)
  await page.goto("/subjects")
  await page.getByRole("searchbox").fill(subject)
  await page.getByRole("button", { name: "Удалить" }).click()
  await dialog(page).getByRole("button", { name: "Подтвердить удаление" }).click()
  await expect(dialog(page).getByRole("alert")).toContainText("У предмета есть задания")
  await dialog(page).getByRole("button", { name: "Отмена" }).click()
  await subjectTasks(page, subject)
  for (const confirm of [false, true]) {
    await page.getByRole("button", { name, exact: true }).click()
    await dialog(page).getByRole("button", { name: "Удалить", exact: true }).click()
    await dialog(page).getByRole("button", { name: confirm ? "Подтвердить удаление" : "Отмена" }).click()
    await expect(dialog(page)).toHaveCount(0)
  }
  await page.reload()
  await expect(page.getByRole("button", { name, exact: true })).toHaveCount(0)
  await page.goto("/subjects")
  await page.getByRole("searchbox").fill(subject)
  await page.getByRole("button", { name: "Удалить" }).click()
  await dialog(page).getByRole("button", { name: "Подтвердить удаление" }).click()
  await expect(dialog(page)).toHaveCount(0)
  await expect(page.getByRole("heading", { name: subject })).toHaveCount(0)
})

test("Сервер отклоняет пустое название и устаревшую правку", async ({ page, context }) => {
  const subject = await createSubject(page)
  const second = await context.newPage()
  for (const tab of [page, second]) {
    await tab.goto("/subjects")
    await tab.getByRole("searchbox").fill(subject)
    await tab.getByRole("button", { name: "Изменить" }).click()
  }
  await dialog(page).getByLabel("Название дисциплины").fill("   ")
  await dialog(page).getByRole("button", { name: "Сохранить" }).click()
  await expect(dialog(page).getByRole("alert")).toHaveText("Введите название.")
  await dialog(page).getByLabel("Название дисциплины").fill(subject)
  await dialog(page).getByLabel("Преподаватель").fill("Проверка версии")
  await dialog(page).getByRole("button", { name: "Сохранить" }).click()
  await expect(dialog(page)).toHaveCount(0)
  await dialog(second).getByRole("button", { name: "Сохранить" }).click()
  await expect(dialog(second).getByRole("alert")).toContainText("Запись уже изменена")
})

test("Этапы, долг, источник, история и главная на мобильном экране", async ({page})=>{
  await page.setViewportSize({width:390,height:844})
  const subject = await createSubject(page)
  await subjectTasks(page,subject)
  const name = fixtureName("этапы")
  const panel = dialog(page)
  await page.getByRole("button",{name:"Добавить задание"}).click()
  await panel.getByLabel("Название задания").fill(name)
  await panel.getByLabel("Подтверждённая задолженность").check()
  for(const [i,title] of ["Чертёж","Проверка"].entries()){
    await panel.getByRole("button",{name:"Добавить этап"}).click()
    await panel.getByLabel("Название этапа "+(i+1)).fill(title)
  }
  await panel.getByLabel("Выполнен этап 1").check()
  await panel.getByRole("button",{name:"Добавить источник"}).click()
  await panel.getByLabel("Название источника").fill("Личная заметка")
  await panel.getByRole("button",{name:"Сохранить"}).click()
  await expect(panel).toHaveCount(0)
  await page.reload()
  const debtFilter = page.getByRole("combobox", { name: "Задолженность", exact: true })
  await debtFilter.selectOption("ordinary")
  await expect(page.getByRole("button",{name,exact:true})).toHaveCount(0)
  await debtFilter.selectOption("debt")
  await expect(page.getByText("1 из 2",{exact:true})).toBeVisible()
  await page.getByRole("button",{name,exact:true}).click()
  await expect(panel.getByText(/Личная заметка · Без подтверждения/)).toBeVisible()
  await panel.getByRole("button",{name:"Изменить"}).click()
  await panel.getByLabel("Статус",{exact:true}).selectOption("В процессе")
  await panel.getByRole("button",{name:"Поднять этап"}).last().click()
  await expect(panel.getByLabel("Название этапа 1")).toHaveValue("Проверка")
  await panel.getByRole("button",{name:"Сохранить"}).click()
  await expect(panel).toHaveCount(0)
  await page.goto("/")
  const debts = page.getByRole("region", { name: "Академические задолженности" })
  await expect(debts).toContainText("1 из 2")
  await debts.getByRole("link", { name: new RegExp(name) }).click()
  await panel.getByText("История изменений").click()
  await expect(panel.getByText(/Статус: Не выяснено → В процессе/)).toBeVisible()
  await expect(panel.getByText(/Этап «Чертёж»: выполнен/)).toBeVisible()
})
